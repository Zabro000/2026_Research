/**
  * @brief  Function implementing the Task1 thread.
  * @param  argument: Not used
  * @retval None
  */
/* USER CODE END Header_StartTask1 */
void StartTask1(void *argument)
{
  /* USER CODE BEGIN 5 */
  /* Infinite loop */
	uint8_t ADDR = 0x68;
	uint8_t ADDR_SHIFT = ADDR << 1;
	static uint8_t MEM_ADDR_SIZE = 1;
	static uint8_t DATA_SIZE = 1;
	uint8_t data_var;
	static uint8_t good_message[] = "IC is connected\n";
	float final_number;
	uint8_t print_number;

	serial_message_print(good_message, sizeof(good_message));

	HAL_I2C_Mem_Read_IT(&hi2c1, ADDR_SHIFT, 0x75, MEM_ADDR_SIZE, &data_var, DATA_SIZE);
	if (data_var == ADDR)
	{
		serial_message_print(good_message, sizeof(good_message));
	}

	///IC Config start
	data_var = 0;
	HAL_I2C_Mem_Write_IT(&hi2c1, ADDR_SHIFT, 0x6B, 1, &data_var, DATA_SIZE);

	data_var = 0x07;
	HAL_I2C_Mem_Write_IT(&hi2c1, ADDR_SHIFT, 0x19, MEM_ADDR_SIZE, &data_var, DATA_SIZE);

	data_var = 0;
	HAL_I2C_Mem_Write_IT(&hi2c1, ADDR_SHIFT, 0x1B, MEM_ADDR_SIZE, &data_var, DATA_SIZE);
	HAL_I2C_Mem_Write_IT(&hi2c1, ADDR_SHIFT, 0x1C, MEM_ADDR_SIZE, &data_var, DATA_SIZE);

	///IC Config complete







  for(;;)
  {

	  IC_read_data(ADDR_SHIFT, &final_number);
	  print_number = (uint8_t)final_number;
	  serial_message_print(&print_number, sizeof(print_number));

	  osDelay(10);
  }
  /* USER CODE END 5 */
}

